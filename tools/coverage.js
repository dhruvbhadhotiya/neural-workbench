#!/usr/bin/env node
/* ==========================================================================
   DeepLearn Lab - tools/coverage.js
   Compares docs/CONTENT_PLAN.md (the promise) with what is on disk (the site):
   lessons, labs, registered widget ids, exams. Rewrites docs/COVERAGE.md.
   Run: node tools/coverage.js [--write]
   Exit code 1 when anything planned is missing.
   ========================================================================== */
"use strict";

var fs = require("fs");
var path = require("path");

var root = path.join(__dirname, "..");
var write = process.argv.indexOf("--write") >= 0;

var plan = fs.readFileSync(path.join(root, "docs", "CONTENT_PLAN.md"), "utf8").split(/\r?\n/);

var modules = [];      // {num, dir, accent, lessons: []}
var lessons = [];      // {id, title, mod, labs: []}
var currentModule = null;
var currentLesson = null;
var inLabs = false;

plan.forEach(function (line) {
  var hm = /^# M(\d)\s+.*?\(`([a-z0-9-]+)`\)/.exec(line);
  if (hm) {
    currentModule = { num: "m" + hm[1], dir: hm[2], lessons: [] };
    modules.push(currentModule);
    currentLesson = null;
    inLabs = false;
    return;
  }
  var lm = /^## (m\d-\d\d-[a-z0-9-]+)\s+[—-]\s+(.+)$/.exec(line);
  if (lm) {
    currentLesson = { id: lm[1], title: lm[2].trim(), mod: currentModule, labs: [] };
    lessons.push(currentLesson);
    currentModule.lessons.push(currentLesson);
    inLabs = false;
    return;
  }
  if (/^\*\*Labs\*\*/.test(line)) { inLabs = true; }
  else if (/^\*\*/.test(line) || /^#/.test(line)) { inLabs = false; }

  if (inLabs) {
    var re = /`(m\d-\d\d-[a-z0-9-]+)`/g, m;
    while ((m = re.exec(line))) {
      if (currentLesson && currentLesson.labs.indexOf(m[1]) < 0) currentLesson.labs.push(m[1]);
    }
  }
});

/* --------------------------------------------------------------- on disk */
function read(p) { return fs.existsSync(p) ? fs.readFileSync(p, "utf8") : ""; }

var registered = {};   // id -> module dir
modules.forEach(function (mod) {
  var js = read(path.join(root, "modules", mod.dir, "widgets", mod.num + "-widgets.js"));
  js.replace(/register\s*\(\s*["']([^"']+)["']/g, function (_, id) { registered[id] = mod.dir; });
});

var used = {};         // id -> lesson id
var htmlIds = {};      // lesson id -> [ids]
modules.forEach(function (mod) {
  mod.lessons.forEach(function (l) {
    var html = read(path.join(root, "modules", mod.dir, l.id + ".html"));
    var ids = [];
    html.replace(/<section class="lab"[^>]*data-widget="([^"]+)"/g, function (_, id) { ids.push(id); });
    htmlIds[l.id] = ids;
    ids.forEach(function (id) { used[id] = l.id; });
  });
});

/* ---------------------------------------------------------------- report */
var gaps = [];
var rows = [];

modules.forEach(function (mod) {
  rows.push("### " + mod.num.toUpperCase() + " (`" + mod.dir + "`)");
  rows.push("");
  rows.push("| lesson | html | labs planned | labs in HTML | registered |");
  rows.push("|---|---|---|---|---|");
  mod.lessons.forEach(function (l) {
    var file = path.join(root, "modules", mod.dir, l.id + ".html");
    var hasFile = fs.existsSync(file);
    if (!hasFile) gaps.push("missing lesson file: " + l.id);
    var inHtml = htmlIds[l.id] || [];
    var regd = l.labs.filter(function (id) { return registered[id]; });
    l.labs.forEach(function (id) {
      if (!registered[id]) gaps.push("widget not registered: " + id + " (" + l.id + ")");
      if (inHtml.indexOf(id) < 0) gaps.push("widget not mounted in " + l.id + ": " + id);
    });
    inHtml.forEach(function (id) {
      if (l.labs.indexOf(id) < 0) gaps.push("lab not in plan for " + l.id + ": " + id);
    });
    rows.push("| " + l.id + " | " + (hasFile ? "yes" : "**no**") + " | " + l.labs.length +
      " | " + inHtml.length + " | " + regd.length + "/" + l.labs.length + " |");
  });
  var exam = read(path.join(root, "modules", mod.dir, "index.html"));
  var hasExam = /data-quiz="m\d-exam"/.test(exam);
  if (!hasExam) gaps.push("missing module exam page: " + mod.dir + "/index.html");
  rows.push("| module index + exam | " + (hasExam ? "yes" : "**no**") + " | — | — | — |");
  rows.push("");
});

var plannedLabs = 0;          // lab sections promised (a reused lab counts per lesson)
lessons.forEach(function (l) { plannedLabs += l.labs.length; });
var plannedUnique = {};       // unique widget ids promised
lessons.forEach(function (l) { l.labs.forEach(function (id) { plannedUnique[id] = 1; }); });
var presentLessons = lessons.filter(function (l) {
  return fs.existsSync(path.join(root, "modules", l.mod.dir, l.id + ".html"));
}).length;
var presentLabs = 0;          // lab sections on disk
lessons.forEach(function (l) { presentLabs += (htmlIds[l.id] || []).length; });
var presentReg = Object.keys(registered).length;

var summary = [
  "# Coverage",
  "",
  "Generated by `node tools/coverage.js --write` from `docs/CONTENT_PLAN.md` and the files on disk.",
  "",
  "- Lessons: **" + presentLessons + " / " + lessons.length + "**",
  "- Labs mounted in HTML: **" + presentLabs + " / " + plannedLabs + "** (lab sections)",
  "- Widget ids registered: **" + presentReg + " / " + Object.keys(plannedUnique).length +
    "** (unique ids; one lab is intentionally reused in m2-06)",
  "- Modules with an exam page: **" + modules.filter(function (mod) {
    return /data-quiz="m\d-exam"/.test(read(path.join(root, "modules", mod.dir, "index.html")));
  }).length + " / " + modules.length + "**",
  "- Gaps: **" + gaps.length + "**",
  ""
].concat(rows).join("\n") + "\n";

if (write) fs.writeFileSync(path.join(root, "docs", "COVERAGE.md"), summary, "utf8");

console.log("lessons " + presentLessons + "/" + lessons.length +
  "  labs(mounted) " + presentLabs + "/" + plannedLabs +
  "  registered " + presentReg + "/" + Object.keys(plannedUnique).length);
gaps.forEach(function (g) { console.log("GAP  " + g); });
console.log(gaps.length ? gaps.length + " gap(s)" : "PASS - plan fully covered");
process.exit(gaps.length ? 1 : 0);
